"""P3: 20-seed synthetic sys-ID Monte Carlo (turbulence + noise), plus bias studies. Writes runs/<id>/ and numbers.

Cases:  main     : 20 seeds, light turbulence (u + w), sensor noise, vane alpha
        no_vane  : same flights, alpha from attitude + EKF velocity - steady wind estimate
        calm_w   : 20 seeds, vertical gusts off (shows the energy-method vertical-air bias)
        alt18km  : 4 seeds at 18 km (rho 0.12), speeds scaled by 1/sqrt(sigma), same pipeline
"""
import json, sys, pathlib, time
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np
import pandas as pd
from flightloop.config import cfg, run_id as make_rid, put_number
from flightloop.sim import truth as TR, maneuvers as M, sensors as SEN
from flightloop.logs import schema
from flightloop.sysid import glide, equation_error as EE, output_error as OE, ci as CI
from flightloop.sysid.common import no_vane_alpha
from flightloop.atmos import isa

C = cfg(); SC = C["sysid"]
p = TR.load(); TRUTH = TR.truth_params(p)
AC = {"S": p["S"], "c": p["c"], "b": p["b"], "mass": p["mass"], "Iyy": p["Iyy"]}
SCRIPT = "scripts/run_sysid_synth.py"


def make_logs(rid, tag, n, seed, speeds, alt0, vertical=True):
    d = ROOT / "runs" / rid / "logs" / tag; d.mkdir(parents=True, exist_ok=True)
    rec = M.fly(p, n, seed, speeds, alt0=alt0, rate=SC["sim_rate_hz"], log_rate=SC["log_rate_hz"], vertical_gusts=vertical)
    rec["h"] = rec["h"]
    rng = np.random.default_rng(seed + 1000)
    sen = SEN.apply(rec, SC, rng, n)
    paths = []
    for i in range(n):
        df = pd.DataFrame({k: sen[k][:, i] for k in ("t", "ax", "ay", "az", "p", "q", "r", "phi", "theta", "psi", "vn", "ve", "vd",
                                                    "h_baro", "tas", "wn", "we", "de", "da", "dr", "throttle")})
        df["alpha"] = sen["alpha_vane"][:, i]
        df["beta"] = rec["beta"][:, i]
        df["maneuver_id"] = rec["seg"][:, i]
        meta = {"source": "synthetic", "aircraft": "StratoGlide design model (inputs/stratoglide/derivs.json)",
                "license": "generated by FlightLoop", "seed": int(seed), "flight_index": i, "derived_fields": {"alpha": "vane (simulated)"},
                "segments": rec["segments"], "turbulence": "MIL-F-8785C light, low altitude, u+w" + ("" if vertical else " (w off)"),
                "units": {"de": "rad"}}
        pth = schema.write(df, d / f"flight_s{seed}_{i:02d}.parquet", meta)
        paths.append(pth)
        # truth side-file for diagnostics only (never read by estimators or the loop engine)
        np.save(d / f"truthdiag_s{seed}_{i:02d}_gustw.npy", rec["gust_w"][:, i])
    return paths, rec, sen


def analyse(path, alpha_mode="vane", do_oe=True, boot=True):
    df, meta = schema.read(path)
    alpha = df["alpha"].to_numpy() if alpha_mode == "vane" else no_vane_alpha(df)
    segs = meta["segments"]
    mid = df["maneuver_id"].to_numpy()
    # quasi-steady windows = the scheduled steady-glide segments (attitude hold, no excitation), each split into
    # three 5 s windows. The threshold detector (|dV/dt| < 0.15, |q| < 0.03) rejected almost every window under
    # light turbulence (HONEST_LOG deviation 7).
    wins = []
    for i, sg in enumerate(segs):
        if sg[1] == "glide":
            ii = np.where(mid == i)[0]
            edges = np.linspace(ii[0], ii[-1] + 1, 4).astype(int)
            wins += [(int(edges[j]), int(edges[j + 1])) for j in range(3)]
    gf = glide.estimate(df, AC, alpha, "force", wins)
    ge = glide.estimate(df, AC, alpha, "energy", wins)
    ee = EE.estimate(df, AC, alpha)
    out = {"glide_force": {k: v for k, v in gf.items() if k not in ("windows", "points")},
           "glide_energy": {k: v for k, v in ge.items() if k not in ("windows", "points")}, "ee": ee}
    exc = [(int(np.where(mid == i)[0][0]), int(np.where(mid == i)[0][-1]) + 1) for i, s in enumerate(segs) if s[1] in ("3211", "211", "doublet")]
    if do_oe:
        th0 = np.array([ee["CLa"], ee["Cma"], ee["Cmq"], ee["Cmde"]])
        out["oe"] = OE.estimate(df, AC, alpha, exc, ee["CLde"], th0)
    if boot:
        blocks = [np.arange(np.where(mid == i)[0][0], np.where(mid == i)[0][-1] + 1) for i in range(len(segs))]
        def fn(bl):
            idx = np.concatenate(bl)
            sub = df.iloc[idx].reset_index(drop=True)
            r = EE.estimate(sub, AC, alpha[idx], L=0)
            return {"CLa": r["CLa"], "Cma": r["Cma"], "Cmde": r["Cmde"]}
        out["boot_ee"] = CI.block_bootstrap(fn, blocks, n_boot=100)
    out["n_windows"] = len(wins)
    return out


def summarize(results, key_map):
    errs = {}
    for name, (grp, k, truth) in key_map.items():
        vals = np.array([r[grp][k] for r in results])
        errs[name] = {"median_abs_err_pct": float(np.median(np.abs(vals - truth) / abs(truth)) * 100),
                      "median_est": float(np.median(vals)), "truth": float(truth), "values": vals.tolist()}
    return errs


def main():
    rid = make_rid("sysid", "synth20")
    out_dir = ROOT / "runs" / rid; out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "config_snapshot.json").write_text(json.dumps({"sysid": SC, "truth": TRUTH}, indent=1))
    t0 = time.time()
    n = SC["seeds"]
    paths, rec, sen = make_logs(rid, "main", n, 101, SC["speeds_ms"], SC["start_alt_m"])
    # parquet round-trip exactness check (V14 synthetic)
    df0, _ = schema.read(paths[0])
    rt_ok = bool(np.array_equal(df0["q"].to_numpy(), sen["q"][:, 0]) and np.array_equal(df0["tas"].to_numpy(), sen["tas"][:, 0]))
    main_res = [analyse(pth) for pth in paths]
    nv_res = [analyse(pth, "novane", do_oe=False, boot=False) for pth in paths]
    paths_c, _, _ = make_logs(rid, "calm_w", n, 202, SC["speeds_ms"], SC["start_alt_m"], vertical=False)
    calm_res = [analyse(pth, do_oe=False, boot=False) for pth in paths_c]
    sig18 = float(isa([18000])["rho"][0] / 1.225)
    sp18 = [v / np.sqrt(sig18) for v in SC["speeds_ms"]]
    paths_h, _, _ = make_logs(rid, "alt18km", 4, 303, sp18, 18000.0 + 900.0)
    h_res = [analyse(pth, do_oe=False, boot=False) for pth in paths_h]
    km = {"CD0": ("glide_force", "CD0", TRUTH["CD0"]), "k": ("glide_force", "k", TRUTH["k"]),
          "CLa": ("ee", "CLa", TRUTH["CLa"]), "Cma": ("ee", "Cma", TRUTH["Cma"]), "Cmde": ("ee", "Cmde", TRUTH["Cmde"]),
          "Cmq": ("ee", "Cmq", TRUTH["Cmq"])}
    S_main = summarize(main_res, km)
    S_energy = summarize(main_res, {"CD0": ("glide_energy", "CD0", TRUTH["CD0"]), "k": ("glide_energy", "k", TRUTH["k"])})
    S_energy_calm = summarize(calm_res, {"CD0": ("glide_energy", "CD0", TRUTH["CD0"]), "k": ("glide_energy", "k", TRUTH["k"])})
    S_nv = summarize(nv_res, {k: v for k, v in km.items() if k in ("CLa", "Cma", "Cmde", "Cmq", "CD0", "k")})
    S_oe = summarize(main_res, {k: ("oe", k, TRUTH[k]) for k in ("CLa", "Cma", "Cmq", "Cmde")})
    S_18 = summarize(h_res, km)
    # coverage (V16)
    cov = {}
    for k, grp, sek in (("CD0", "glide_force", "se_CD0"), ("CLa", "ee", "se_CLa"), ("Cma", "ee", "se_Cma")):
        tk = {"CD0": "CD0", "CLa": "CLa", "Cma": "Cma"}[k]
        kk = {"CD0": "CD0", "CLa": "CLa", "Cma": "Cma"}[k]
        hits = [CI.covers(r[grp][kk], r[grp][sek], TRUTH[tk]) for r in main_res]
        cov[k] = float(np.mean(hits) * 100)
    # secondary, post hoc (HONEST_LOG 10): CI that adds the per-flight airspeed-calibration term from the pitot-scale
    # spec in quadrature (CD0, CLa, Cma all scale with 1/q_bar, i.e. 2 x the TAS scale error). Not the V16 definition.
    ps = SC["sensor_noise"]["pitot_scale"]
    cov_cal = {}
    for k, grp, sek in (("CD0", "glide_force", "se_CD0"), ("CLa", "ee", "se_CLa"), ("Cma", "ee", "se_Cma")):
        hits = [CI.covers(r[grp][k], float(np.hypot(r[grp][sek], 2 * ps * abs(r[grp][k]))), TRUTH[k]) for r in main_res]
        cov_cal[k] = float(np.mean(hits) * 100)
    cov_boot = {k: float(np.mean([(r["boot_ee"][k][0] <= TRUTH[k] <= r["boot_ee"][k][1]) for r in main_res]) * 100) for k in ("CLa", "Cma", "Cmde")}
    nv_bias = {k: float(np.median([(r["ee"][k] - TRUTH[k]) / abs(TRUTH[k]) * 100 for r in nv_res])) for k in ("CLa", "Cma")}
    oe_corr = np.median(np.array([r["oe"]["corr"] for r in main_res]), axis=0).tolist()
    ee_corr = np.median(np.array([r["ee"]["regressor_corr"] for r in main_res]), axis=0).tolist()
    summary = {"run_id": rid, "seeds": n, "parquet_roundtrip_exact": rt_ok, "main": S_main, "energy_method": S_energy,
               "energy_method_no_vertical_gust": S_energy_calm, "no_vane": S_nv, "no_vane_median_bias_pct": nv_bias,
               "output_error": S_oe, "alt18km": S_18, "coverage_pct": cov, "coverage_boot_pct": cov_boot, "coverage_with_calibration_pct": cov_cal,
               "oe_param_corr_median": oe_corr, "ee_regressor_corr_median": ee_corr,
               "wall_s": time.time() - t0, "per_seed": main_res}
    res_dir = ROOT / "results/sysid"; res_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=1, default=float))
    (res_dir / "synthetic_summary.json").write_text(json.dumps({k: v for k, v in summary.items() if k != "per_seed"}, indent=1, default=float))
    (res_dir / "no_vane_bias.json").write_text(json.dumps({"median_bias_pct": nv_bias, "run_id": rid}, indent=1))
    src = "synthetic (StratoGlide design model, FlightLoop sim)"
    for k, v in S_main.items():
        put_number(f"sysid.synth.{k.lower()}_median_err_pct", v["median_abs_err_pct"], "%", SCRIPT, src, rid)
    put_number("sysid.synth.cd0_energy_median_err_pct", S_energy["CD0"]["median_abs_err_pct"], "%", SCRIPT, src, rid)
    put_number("sysid.synth.cd0_energy_calm_median_err_pct", S_energy_calm["CD0"]["median_abs_err_pct"], "%", SCRIPT, src, rid)
    for k, v in cov.items():
        put_number(f"sysid.synth.coverage_{k.lower()}_pct", v, "%", SCRIPT, src, rid)
    for k, v in nv_bias.items():
        put_number(f"sysid.synth.novane_bias_{k.lower()}_pct", v, "%", SCRIPT, src, rid)
    for k, v in S_oe.items():
        put_number(f"sysid.synth.oe_{k.lower()}_median_err_pct", v["median_abs_err_pct"], "%", SCRIPT, src, rid)
    put_number("sysid.synth.n_seeds", n, "-", SCRIPT, src, rid)
    put_number("sysid.synth.alt18km_cd0_median_err_pct", S_18["CD0"]["median_abs_err_pct"], "%", SCRIPT, src, rid)
    put_number("sysid.synth.parquet_roundtrip_exact", rt_ok, "-", SCRIPT, src, rid)
    print(json.dumps({k: v for k, v in summary.items() if k not in ("per_seed",)}, indent=1, default=float)[:6000])


if __name__ == "__main__":
    main()
